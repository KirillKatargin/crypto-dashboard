export const makeRows = (): Coin[] =>
  Array.from({ length: 500 }, (_, i) => {
    const s = seedRows[i % seedRows.length];
    return {
      id: `${s[0]}-${i}`,
      rank: i + 1,
      name: i < seedRows.length ? s[1] : `${s[1]} ${Math.floor(i / seedRows.length) + 1}`,
      symbol: s[2],
      price: s[3],
      day: s[4],
      week: s[5],
      cap: s[6],
      volume: s[7],
      supply: s[8],
      color: s[9],
      image: '',
    };
  });
export const mapApiCoin = (c: Record<string, unknown>, i: number): Coin => ({
  id: String(c.id),
  rank: Number(c.market_cap_rank || i + 1),
  name: String(c.name),
  symbol: String(c.symbol).toUpperCase(),
  image: String(c.image || ''),
  price: Number(c.current_price || 0),
  day: Number(c.price_change_percentage_24h || 0),
  week: Number(c.price_change_percentage_7d_in_currency || 0),
  cap: Number(c.market_cap || 0),
  volume: Number(c.total_volume || 0),
  supply: Number(c.circulating_supply || 0),
  color: ['#8e75e8', '#40d9a1', '#f7931a', '#5c7cfa'][i % 4],
});
